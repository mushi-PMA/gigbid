"""The marketplace port: one interface, two adapters (GigSim and live Upwork), chosen by config."""
from __future__ import annotations

from typing import Any, Protocol


class MarketplaceUnavailable(RuntimeError):
    """The marketplace could not be reached after bounded retries (degraded mode)."""


class MarketplaceRejected(RuntimeError):
    """The marketplace refused the request (validation, policy, insufficient Connects)."""

    def __init__(self, status: int, detail: Any):
        super().__init__(f"{status}: {detail}")
        self.status = status
        self.detail = detail


class MarketplaceAdapter(Protocol):
    name: str

    async def search_jobs(self, query: str, skills: list[str], category: str, since: str | None,
                          limit: int) -> dict[str, Any]: ...
    async def get_job(self, job_id: str) -> dict[str, Any]: ...
    async def get_client_history(self, client_id: str) -> dict[str, Any]: ...
    async def get_connects_balance(self) -> dict[str, Any]: ...
    async def list_threads(self) -> dict[str, Any]: ...
    async def list_messages(self, thread_id: str) -> dict[str, Any]: ...
    async def list_events(self, since: str | None) -> dict[str, Any]: ...
    async def list_proposals(self) -> dict[str, Any]: ...
    async def get_policy(self) -> dict[str, Any]: ...
    async def get_market_pricing(self, category: str, skills: list[str]) -> dict[str, Any]: ...
    async def create_proposal_draft(self, body: dict[str, Any], idempotency_key: str,
                                    dry_run: bool) -> dict[str, Any]: ...
    async def submit_proposal(self, proposal_id: str, idempotency_key: str, dry_run: bool) -> dict[str, Any]: ...
    async def send_message(self, thread_id: str, text: str, idempotency_key: str,
                           dry_run: bool) -> dict[str, Any]: ...
